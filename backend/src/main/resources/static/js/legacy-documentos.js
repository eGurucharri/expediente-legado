    function iconoSvg(tipo) {
        var arte = ICONOS[tipo];
        if (!arte) {
            return null;
        }
        var alto = arte.filas.length;
        var ancho = arte.filas[0].length;
        var rects = "";
        for (var y = 0; y < alto; y++) {
            for (var x = 0; x < ancho; x++) {
                var color = arte.paleta[arte.filas[y].charAt(x)];
                if (color) {
                    rects += "<rect x='" + x + "' y='" + y + "' width='1' height='1' fill='" + color + "'/>";
                }
            }
        }
        return "<svg viewBox='0 0 " + ancho + " " + alto + "' shape-rendering='crispEdges' aria-hidden='true'>" + rects + "</svg>";
    }

